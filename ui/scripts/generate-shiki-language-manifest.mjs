import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { languageAliasNames, languageNames } from "@shikijs/langs";

const here = dirname(fileURLToPath(import.meta.url));
const uiRoot = dirname(here);
const metadataOutput = join(uiRoot, "src/generated-shiki-language-metadata.ts");
const loadersOutput = join(uiRoot, "src/generated-shiki-language-loaders.ts");

async function generatedFile(header, body) {
  return format(
    `${header}\n// This file is generated by scripts/generate-shiki-language-manifest.mjs.\n// Do not edit by hand.\n\n${body}`,
    { parser: "typescript", printWidth: 100, tabWidth: 2, useTabs: false },
  );
}

function writeIfChanged(path, content) {
  try {
    if (readFileSync(path, "utf8") === content) return;
  } catch (error) {
    if (!(error instanceof Error) || !("code" in error) || error.code !== "ENOENT") throw error;
  }
  writeFileSync(path, content);
}

async function bundledLanguageLabels() {
  const labels = new Map(languageNames.map((name) => [name, name]));

  for (const name of languageNames) {
    const { default: registrations } = await import(`@shikijs/langs/${name}`);
    const registration = registrations.find((language) => language.name === name);
    if (!registration)
      throw new Error(`Shiki bundled language ${name} has no matching registration`);
    for (const alias of registration.aliases ?? []) labels.set(alias, name);
  }

  for (const alias of languageAliasNames) {
    if (!labels.has(alias))
      throw new Error(`Shiki bundled alias ${alias} was not found in its grammar metadata`);
  }
  return labels;
}

function objectEntries(entries) {
  return [...entries]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([label, name]) => `  ${JSON.stringify(label)}: ${JSON.stringify(name)},`)
    .join("\n");
}

export async function generateShikiLanguageManifest() {
  const labels = await bundledLanguageLabels();
  const metadata = await generatedFile(
    "// Authoritative labels from @shikijs/langs bundled grammar registrations.",
    `export const SHIKI_LANGUAGE_BY_LABEL: Readonly<Record<string, string>> = Object.freeze({\n${objectEntries(labels)}\n});\n`,
  );
  const loaders = await generatedFile(
    "// Lazy loaders for every @shikijs/langs bundled canonical grammar.",
    `export const SHIKI_LANGUAGE_LOADERS = Object.freeze({\n${languageNames
      .map(
        (name) =>
          `  ${JSON.stringify(name)}: () => import("@shikijs/langs/${name}").then(({ default: language }) => language),`,
      )
      .join("\n")}\n});\n`,
  );

  writeIfChanged(metadataOutput, metadata);
  writeIfChanged(loadersOutput, loaders);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateShikiLanguageManifest();
}
