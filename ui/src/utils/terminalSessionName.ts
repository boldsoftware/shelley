/** A random color name that isn't one of existing. */
export function mintSessionName(existing: readonly string[]): string {
  const free = colorNames.filter((n) => !existing.includes(n));
  if (!free.length) throw new Error("every terminal session name is taken");
  return free[Math.floor(Math.random() * free.length)];
}
