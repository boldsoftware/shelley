func TestGenerate(t *testing.T) {
	src, err := generate([]byte(`
filter = '''
(matchesAny(finding["secret"], [
  ` + "`^true$`, `AIza" + "Sy0123456789abcdefghijklmnopqrstuvw`" + `
]) || containsAny(finding["secret"], ["abcdefghijklmnopqrstuvwxyz"]))
'''
[[rules]]
id = "acme-token.1"
regex = '''\b(acme_[a-z0-9]{8})\b'''
keywords = ["ACME_"]
filter = '''
entropy(finding["secret"]) <= 2.5
|| filter.tokenRatio(finding["secret"]) >= 2.5
|| !matchesAny(finding["secret"], ["[0-9]", "x"])
|| matchesAny(finding["match"], [` + "`EXAMPLE`" + `])
|| matchesAny(attributes["path"], [` + "`README`" + `])
'''
[[rules]]
id = "generic-api-key"
regex = '''x'''
[[rules]]
id = "acme-id"
regex = '''y'''
skipReport = true
[[rules]]
id = "acme-file"
regex = '''y'''
path = '''\.acme$'''
`))
	if err != nil {
		t.Fatal(err)
	}
	// With ' for `.
	want := strings.ReplaceAll(`
package secretdetect

var knownGlobalAllow = allowSpec{
	regexes: []string{
		"^true$",
		"\x41IzaSy0123456789abcdefghijklmnopqrstuvw",
	},
	stopwords: []string{
		"abcdefghijklmnopqrstuvwxyz",
	},
}

var knownRules = []ruleSpec{
	{
		kind:     "acme-token",
		label:    "Acme token",
		regex:    '\b(acme_[a-z0-9]{8})\b',
		keywords: []string{"acme_"},
		entropy:  2.5,
		wordy:    true,
		require: []string{
			"(?:[0-9])|(?:x)",
		},
		allow: []allowSpec{
			{
				match: true,
				regexes: []string{
					"EXAMPLE",
				},
			},
		},
	},
}
`, "'", "`")
	s := string(src)
	if !strings.HasPrefix(s, "// Code generated by cmd/secretrules; DO NOT EDIT.\n") || !strings.Contains(s, "MIT License") {
		t.Errorf("header missing in\n%s", s)
	}
	if _, got, _ := strings.Cut(s, "SOFTWARE.\n"); got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
}

func TestUnsupportedFilter(t *testing.T) {
	_, err := generate([]byte(`
[[rules]]
id = "acme-token"
regex = '''acme_[a-z]{8}'''
filter = '''len(finding["secret"]) > 3'''
`))
	if err == nil || !strings.Contains(err.Error(), "unsupported filter term") {
		t.Errorf("err = %v, want unsupported filter term", err)
	}
}

func TestGoString(t *testing.T) {
	for _, tc := range []struct{ s, want string }{
		{"abc", `"abc"`},
		{`\d+`, "`\\d+`"},
		{"a`\\", `"a` + "`" + `\\"`},
		{`\b` + "AKIA" + `0123456789ABCDEF\b`, `"\\b\x41KIA0123456789ABCDEF\\b"`},
		{"\r" + "rk_live_" + "0123456789abcdef", `"\r\x72k_live_0123456789abcdef"`},
	} {
		if got := goString(tc.s); got != tc.want {
			t.Errorf("goString(%q) = %s, want %s", tc.s, got, tc.want)
		}
	}
}

func TestBadRegex(t *testing.T) {
	_, err := generate([]byte(`
[[rules]]
id = "acme-token"
regex = '''a{2000}'''
`))
	if err == nil || !strings.Contains(err.Error(), "acme-token") {
		t.Errorf("err = %v, want acme-token's regex error", err)
	}
}
