// Command secretrules generates secretdetect/generated_rules.go, the
// known-format secret rules (docs/secrets.md), from betterleaks' default
// configuration:
//
//	go run ./cmd/secretrules -o secretdetect/generated_rules.go
//
// It keeps the provider-specific rules: not the generic ones (which flag
// ordinary assignments), component-only rules (IDs, URLs), or rules scoped
// to file paths. Filters (Expr) are translated term by term, and a term
// this doesn't know fails the generation.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"strconv"
	"strings"

	"github.com/BurntSushi/toml"
)

// The betterleaks release the rules come from.
const version = "v1.10.1"

const source = "https://raw.githubusercontent.com/betterleaks/betterleaks/" + version + "/config/betterleaks.toml"

// Rules left out: the generic ones match any key = value, password or
// URL with credentials, and box-api-access-token's filter reads the text
// around the match. Shelley's own random-token rule covers random values
// more conservatively.
var skip = map[string]bool{
	"generic-api-key":        true,
	"generic-credential-uri": true,
	"generic-password":       true,
	"generic-username":       true,
	"box-api-access-token":   true,
	"kubernetes-secret-yaml": true,
}

// The longest kind the server accepts (server/secrets.go): a secret's ID is
// its kind and five characters, at most 64.
const maxKind = 59

type rule struct {
	ID          string   `toml:"id"`
	Regex       string   `toml:"regex"`
	Path        string   `toml:"path"`
	SecretGroup int      `toml:"secretGroup"`
	Keywords    []string `toml:"keywords"`
	Filter      string   `toml:"filter"`
	SkipReport  bool     `toml:"skipReport"`
}

type config struct {
	Filter string `toml:"filter"`
	Rules  []rule `toml:"rules"`
}

// allow is an allowlist, as secretdetect's allowSpec.
type allow struct {
	match     bool
	regexes   []string
	stopwords []string
}

func main() {
	out := flag.String("o", "", "the Go file to write")
	flag.Parse()
	if *out == "" {
		log.Fatal("usage: go run ./cmd/secretrules -o secretdetect/generated_rules.go")
	}
	resp, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", source, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	src, err := generate(data)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func generate(data []byte) ([]byte, error) {
	var cfg config
	if err := toml.Unmarshal(data, &cfg); err != nil {
		return nil, err
	}
	global, err := parseFilter(cfg.Filter)
	if err != nil {
		return nil, fmt.Errorf("global filter: %w", err)
	}
	if global.entropy != 0 || global.wordy || len(global.require) > 0 || global.match.regexes != nil {
		return nil, fmt.Errorf("global filter: only secret regexes and stopwords are supported")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by cmd/secretrules; DO NOT EDIT.

// Known secret formats, from betterleaks %s (config/betterleaks.toml).
// Regenerate with:
//
//	go run ./cmd/secretrules -o secretdetect/generated_rules.go
//
// Betterleaks is MIT licensed:
//
`, version)
	for _, line := range strings.Split(strings.TrimSpace(mitLicense), "\n") {
		fmt.Fprintf(&b, "//\t%s\n", line)
	}
	b.WriteString("\npackage secretdetect\n\nvar knownGlobalAllow = allowSpec")
	writeAllow(&b, global.secret)
	b.WriteString("\n\nvar knownRules = []ruleSpec{\n")
	for _, r := range cfg.Rules {
		if skip[r.ID] || r.SkipReport || r.Path != "" || r.Regex == "" {
			continue
		}
		// Variants of a rule are id.1, id.2: one kind.
		kind := regexp.MustCompile(`\.[0-9]+$`).ReplaceAllString(r.ID, "")
		if len(kind) > maxKind || !regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`).MatchString(kind) {
			return nil, fmt.Errorf("rule id %q is not a valid secret kind", r.ID)
		}
		if _, err := regexp.Compile(r.Regex); err != nil {
			return nil, fmt.Errorf("%s: %w", r.ID, err)
		}
		f, err := parseFilter(r.Filter)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", r.ID, err)
		}
		fmt.Fprintf(&b, "{\nkind: %s,\nlabel: %s,\nregex: %s,\nkeywords: []string{", goString(kind), goString(label(kind)), goString(r.Regex))
		for i, k := range lower(r.Keywords) {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(goString(k))
		}
		b.WriteString("},\n")
		if r.SecretGroup != 0 {
			fmt.Fprintf(&b, "secretGroup: %d,\n", r.SecretGroup)
		}
		if f.entropy != 0 {
			fmt.Fprintf(&b, "entropy: %s,\n", strconv.FormatFloat(f.entropy, 'g', -1, 64))
		}
		if f.wordy {
			b.WriteString("wordy: true,\n")
		}
		if f.require != nil {
			b.WriteString("require: ")
			writeStrings(&b, f.require)
			b.WriteString(",\n")
		}
		if f.secret.regexes != nil || f.secret.stopwords != nil || f.match.regexes != nil {
			b.WriteString("allow: []allowSpec{\n")
			for _, a := range []allow{f.secret, f.match} {
				if a.regexes != nil || a.stopwords != nil {
					writeAllow(&b, a)
					b.WriteString(",\n")
				}
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func writeAllow(b *bytes.Buffer, a allow) {
	b.WriteString("{\n")
	if a.match {
		b.WriteString("match: true,\n")
	}
	if a.regexes != nil {
		b.WriteString("regexes: ")
		writeStrings(b, a.regexes)
		b.WriteString(",\n")
	}
	if a.stopwords != nil {
		b.WriteString("stopwords: ")
		writeStrings(b, a.stopwords)
		b.WriteString(",\n")
	}
	b.WriteString("}")
}

func writeStrings(b *bytes.Buffer, list []string) {
	b.WriteString("[]string{\n")
	for _, s := range list {
		fmt.Fprintf(b, "%s,\n", goString(s))
	}
	b.WriteString("}")
}

// goString is s as a Go string literal, raw rather than with escapes, and
// with the first character of anything that looks like a live API key to
// secret scanners (allowlists hold example keys, e.g. Google's published
// ones) escaped, so the source holds no key-shaped literal and pushing it
// trips no scanner.
func goString(s string) string {
	keys := keyLike.FindAllStringIndex(s, -1)
	if q := strconv.Quote(s); keys == nil && !strings.Contains(q, `\`) {
		return q
	}
	if keys == nil && strconv.CanBackquote(s) {
		return "`" + s + "`"
	}
	var b strings.Builder
	quote := func(s string) {
		q := strconv.Quote(s)
		b.WriteString(q[1 : len(q)-1])
	}
	b.WriteByte('"')
	last := 0
	for _, k := range keys {
		quote(s[last:k[0]])
		fmt.Fprintf(&b, `\x%02x`, s[k[0]])
		last = k[0] + 1
	}
	quote(s[last:])
	b.WriteByte('"')
	return b.String()
}

var keyLike = regexp.MustCompile(`(sk-|AIza|AKIA|gh[pousr]_|github_pat_|[sr]k_live_)[A-Za-z0-9_-]{16,}`)

// filter is a translated filter (an Expr expression): a finding is dropped
// when any of its || terms holds.
type filter struct {
	entropy float64
	wordy   bool
	require []string
	secret  allow
	match   allow
}

var (
	entropyTerm = regexp.MustCompile(`^(?:filter\.)?entropy\(finding\["secret"\]\) <=? ([0-9.]+)$`)
	// The secret's length per BPE token: high for words. Shelley
	// approximates it (secretdetect's wordy).
	ratioTerm = regexp.MustCompile(`^(?:filter\.)?tokenRatio\(finding\["secret"\]\) >= 2\.5$`)
	listTerm  = regexp.MustCompile(`^(!?)(?:filter\.)?(matchesAny|containsAny)\((finding|attributes)\["(\w+)"\], \[([\s\S]*)\]\)$`)
)

func parseFilter(expr string) (filter, error) {
	var f filter
	terms, err := orTerms(expr)
	if err != nil {
		return f, err
	}
	for _, term := range terms {
		if m := entropyTerm.FindStringSubmatch(term); m != nil {
			if f.entropy, err = strconv.ParseFloat(m[1], 64); err != nil {
				return f, err
			}
			continue
		}
		if ratioTerm.MatchString(term) {
			f.wordy = true
			continue
		}
		m := listTerm.FindStringSubmatch(term)
		if m == nil {
			return f, fmt.Errorf("unsupported filter term %q", term)
		}
		not, fn, target := m[1] == "!", m[2], m[3]+"."+m[4]
		if target == "attributes.path" && !not {
			continue // typed text has no path
		}
		items, err := listItems(m[5])
		if err != nil {
			return f, fmt.Errorf("%q: %w", term, err)
		}
		switch {
		case not && fn == "matchesAny" && target == "finding.secret":
			for i, it := range items {
				items[i] = "(?:" + it + ")"
			}
			re := strings.Join(items, "|")
			if _, err := regexp.Compile(re); err != nil {
				return f, err
			}
			f.require = append(f.require, re)
		case !not && fn == "matchesAny" && (target == "finding.secret" || target == "finding.match"):
			a := &f.secret
			if target == "finding.match" {
				a = &f.match
				a.match = true
			}
			for _, it := range items {
				if _, err := regexp.Compile(it); err != nil {
					return f, err
				}
				a.regexes = append(a.regexes, it)
			}
		case !not && fn == "containsAny" && target == "finding.secret":
			f.secret.stopwords = append(f.secret.stopwords, lower(items)...)
		default:
			return f, fmt.Errorf("unsupported filter term %q", term)
		}
	}
	return f, nil
}

// orTerms splits an expression at its top-level ||, unwrapping
// parenthesized disjunctions.
func orTerms(expr string) ([]string, error) {
	expr = strings.TrimSpace(expr)
	if expr == "" {
		return nil, nil
	}
	var terms []string
	depth, start := 0, 0
	for i := 0; i < len(expr); i++ {
		switch c := expr[i]; c {
		case '`', '"':
			j := i + 1
			for ; j < len(expr) && expr[j] != c; j++ {
				if c == '"' && expr[j] == '\\' {
					j++
				}
			}
			if j >= len(expr) {
				return nil, fmt.Errorf("unterminated string in %q", expr)
			}
			i = j
		case '(', '[':
			depth++
		case ')', ']':
			depth--
		case '|':
			if depth == 0 && i+1 < len(expr) && expr[i+1] == '|' {
				terms = append(terms, strings.TrimSpace(expr[start:i]))
				start = i + 2
				i++
			}
		}
	}
	terms = append(terms, strings.TrimSpace(expr[start:]))
	if len(terms) == 1 && strings.HasPrefix(expr, "(") && strings.HasSuffix(expr, ")") {
		if inner, err := orTerms(expr[1 : len(expr)-1]); err == nil && len(inner) > 1 {
			return inner, nil
		}
	}
	var out []string
	for _, t := range terms {
		if len(terms) > 1 && strings.HasPrefix(t, "(") && strings.HasSuffix(t, ")") {
			inner, err := orTerms(t[1 : len(t)-1])
			if err != nil {
				return nil, err
			}
			if len(inner) > 1 {
				out = append(out, inner...)
				continue
			}
		}
		out = append(out, t)
	}
	return out, nil
}

// listItems parses a list's strings: `raw` or "quoted".
func listItems(list string) ([]string, error) {
	var items []string
	for s := strings.TrimSpace(list); s != ""; {
		var end int
		switch s[0] {
		case '`':
			end = strings.IndexByte(s[1:], '`') + 2
			if end == 1 {
				return nil, fmt.Errorf("unterminated string")
			}
			items = append(items, s[1:end-1])
		case '"':
			for end = 1; end < len(s) && s[end] != '"'; end++ {
				if s[end] == '\\' {
					end++
				}
			}
			end++
			if end > len(s) {
				return nil, fmt.Errorf("unterminated string")
			}
			it, err := strconv.Unquote(s[:end])
			if err != nil {
				return nil, err
			}
			items = append(items, it)
		default:
			return nil, fmt.Errorf("unexpected %q in list", s)
		}
		s = strings.TrimSpace(s[end:])
		s = strings.TrimSpace(strings.TrimPrefix(s, ","))
	}
	return items, nil
}

func lower(s []string) []string {
	out := make([]string, len(s))
	for i, w := range s {
		out[i] = strings.ToLower(w)
	}
	return out
}

