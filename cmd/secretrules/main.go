// Command secretrules generates ui/src/generated-secret-rules.ts, the
// composer's known-format secret rules (docs/secrets.md), from gitleaks'
// default configuration:
//
//	go run ./cmd/secretrules -o ui/src/generated-secret-rules.ts
//
// It keeps the provider-specific rules: not generic-api-key (which flags
// ordinary assignments) and not rules scoped to file paths. Go (RE2)
// regular expressions are translated to JavaScript through their parsed
// syntax tree, so case folding, classes and anchors keep their meaning.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"regexp/syntax"
	"strings"
	"unicode"

	"github.com/BurntSushi/toml"
)

// The gitleaks release the rules come from.
const version = "v8.30.1"

const source = "https://raw.githubusercontent.com/gitleaks/gitleaks/" + version + "/config/gitleaks.toml"

// Rules left out: generic-api-key matches any key = value with a random
// value, which the composer's own random-token rule covers more
// conservatively.
var skip = map[string]bool{"generic-api-key": true}

// The longest kind the server accepts (server/secrets.go): a secret's ID is
// its kind and five characters, at most 64.
const maxKind = 59

type allowlist struct {
	RegexTarget string   `toml:"regexTarget"`
	Regexes     []string `toml:"regexes"`
	Stopwords   []string `toml:"stopwords"`
	Paths       []string `toml:"paths"`
}

type rule struct {
	ID          string      `toml:"id"`
	Regex       string      `toml:"regex"`
	Path        string      `toml:"path"`
	SecretGroup int         `toml:"secretGroup"`
	Entropy     float64     `toml:"entropy"`
	Keywords    []string    `toml:"keywords"`
	Allowlists  []allowlist `toml:"allowlists"`
}

type config struct {
	Allowlist allowlist `toml:"allowlist"`
	Rules     []rule    `toml:"rules"`
}

// The generated file's shapes, as JSON.
type jsAllow struct {
	Match     bool     `json:"match,omitempty"`
	Regexes   []string `json:"regexes,omitempty"`
	Stopwords []string `json:"stopwords,omitempty"`
}

type jsRule struct {
	ID          string    `json:"id"`
	Label       string    `json:"label"`
	Regex       string    `json:"regex"`
	Keywords    []string  `json:"keywords"`
	SecretGroup int       `json:"secretGroup,omitempty"`
	Entropy     float64   `json:"entropy,omitempty"`
	Allow       []jsAllow `json:"allow,omitempty"`
}

func main() {
	out := flag.String("o", "", "the TypeScript file to write")
	flag.Parse()
	if *out == "" {
		log.Fatal("usage: go run ./cmd/secretrules -o ui/src/generated-secret-rules.ts")
	}
	resp, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", source, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	src, err := generate(data)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	// Formatted like the rest of ui/src, so formatting it is no change.
	abs, err := filepath.Abs(*out)
	if err != nil {
		log.Fatal(err)
	}
	prettier := exec.Command("scripts/with-node", "pnpm", "--dir", "ui", "exec", "prettier", "--write", abs)
	prettier.Stdout, prettier.Stderr = os.Stderr, os.Stderr
	if err := prettier.Run(); err != nil {
		log.Fatalf("prettier: %v", err)
	}
}

func generate(data []byte) ([]byte, error) {
	var cfg config
	if err := toml.Unmarshal(data, &cfg); err != nil {
		return nil, err
	}
	global, err := convertAllow(cfg.Allowlist)
	if err != nil {
		return nil, fmt.Errorf("global allowlist: %w", err)
	}
	var rules []jsRule
	for _, r := range cfg.Rules {
		if skip[r.ID] || r.Path != "" || r.Regex == "" {
			continue
		}
		if len(r.ID) > maxKind || !regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`).MatchString(r.ID) {
			return nil, fmt.Errorf("rule id %q is not a valid secret kind", r.ID)
		}
		re, err := toJS(r.Regex, true)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", r.ID, err)
		}
		jr := jsRule{ID: r.ID, Label: label(r.ID), Regex: re, Keywords: lower(r.Keywords), SecretGroup: r.SecretGroup, Entropy: r.Entropy}
		for _, a := range r.Allowlists {
			if len(a.Regexes) == 0 && len(a.Stopwords) == 0 {
				continue // path-only allowlists don't apply to typed text
			}
			ja, err := convertAllow(a)
			if err != nil {
				return nil, fmt.Errorf("%s allowlist: %w", r.ID, err)
			}
			jr.Allow = append(jr.Allow, ja)
		}
		rules = append(rules, jr)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Known secret formats, from gitleaks %s (config/gitleaks.toml).
// Generated by cmd/secretrules; do not edit. Regenerate with:
//   go run ./cmd/secretrules -o ui/src/generated-secret-rules.ts
//
// Gitleaks is MIT licensed:
//
`, version)
	for _, line := range strings.Split(strings.TrimSpace(mitLicense), "\n") {
		fmt.Fprintf(&b, "//   %s\n", line)
	}
	b.WriteString(`
export interface GitleaksAllow {
  /** The regexes test the whole match, not the secret. */
  match?: boolean;
  regexes?: string[];
  stopwords?: string[];
}

export interface GitleaksRule {
  id: string;
  label: string;
  /** JavaScript source, for the flags "dgu". */
  regex: string;
  /** Lowercase; the rule runs only on text containing one. */
  keywords: string[];
  /** The capture group holding the secret; 0 means the first that matched,
   *  or the whole match. */
  secretGroup?: number;
  /** The secret's minimum Shannon entropy, in bits per character. */
  entropy?: number;
  allow?: GitleaksAllow[];
}

`)
	for _, v := range []struct {
		decl string
		val  any
	}{{"export const GITLEAKS_ALLOW: GitleaksAllow = ", global}, {"export const GITLEAKS_RULES: GitleaksRule[] = ", rules}} {
		j, err := json.MarshalIndent(v.val, "", "  ")
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "%s%s;\n\n", v.decl, keyLike.ReplaceAllStringFunc(string(j), escapeFirst))
	}
	return bytes.TrimRight(b.Bytes(), "\n"), nil
}

// keyLike matches strings that look like live API keys to secret scanners
// (gitleaks' allowlists hold example keys, e.g. Google's published ones).
// They are written with their first character escaped, so the source holds
// no key-shaped literal and pushing it trips no scanner.
var keyLike = regexp.MustCompile(`(sk-|AIza|AKIA|gh[pousr]_|github_pat_|[sr]k_live_)[A-Za-z0-9_-]{16,}`)

func escapeFirst(s string) string { return fmt.Sprintf(`\u%04x`, s[0]) + s[1:] }

func convertAllow(a allowlist) (jsAllow, error) {
	ja := jsAllow{Match: a.RegexTarget == "match", Stopwords: lower(a.Stopwords)}
	switch a.RegexTarget {
	case "", "secret", "match":
	default:
		return ja, fmt.Errorf("regexTarget %q", a.RegexTarget)
	}
	for _, r := range a.Regexes {
		re, err := toJS(r, false)
		if err != nil {
			return ja, err
		}
		ja.Regexes = append(ja.Regexes, re)
	}
	return ja, nil
}

func lower(s []string) []string {
	out := make([]string, len(s))
	for i, w := range s {
		out[i] = strings.ToLower(w)
	}
	return out
}

var acronyms = map[string]string{
	"api": "API", "aws": "AWS", "gcp": "GCP", "jwt": "JWT", "pat": "PAT", "id": "ID", "url": "URL",
	"oauth": "OAuth", "npm": "npm", "pypi": "PyPI", "ci": "CI", "cicd": "CI/CD", "scim": "SCIM",
	"ca": "CA", "openai": "OpenAI", "github": "GitHub", "gitlab": "GitLab", "1password": "1Password",
	"digitalocean": "DigitalOcean", "huggingface": "Hugging Face", "tf": "Terraform", "ptt": "PTT",
	"rrt": "RRT", "ad": "AD", "pkcs12": "PKCS#12", "base64": "base64", "yaml": "YAML",
}

// label makes a rule id readable: github-pat is "GitHub PAT".
func label(id string) string {
	words := strings.Split(id, "-")
	for i, w := range words {
		if a, ok := acronyms[w]; ok {
			words[i] = a
		} else if i == 0 {
			words[i] = strings.ToUpper(w[:1]) + w[1:]
		}
	}
	return strings.Join(words, " ")
}

// toJS translates an RE2 regular expression into JavaScript source for the
// "u" flag, with the same matches. With trim, it drops leading optional
// runs, like the [\w.-]{0,50}? before a keyword (see trimLead).
func toJS(re string, trim bool) (string, error) {
	parsed, err := syntax.Parse(re, syntax.Perl)
	if err != nil {
		return "", err
	}
	if trim {
		trimLead(parsed)
	}
	var b strings.Builder
	if err := emit(&b, parsed); err != nil {
		return "", err
	}
	return b.String(), nil
}

// trimLead drops the optional runs a match starts with, in each branch of a
// leading alternation too: they only move where a match starts, and
// JavaScript's backtracking pays for them at every position (RE2 doesn't),
// making the keyword rules quadratic. Captures stay: they hold the secret.
func trimLead(re *syntax.Regexp) {
	switch re.Op {
	case syntax.OpAlternate:
		for _, sub := range re.Sub {
			trimLead(sub)
		}
	case syntax.OpConcat:
		for len(re.Sub) > 1 && optionalRun(re.Sub[0]) {
			re.Sub = re.Sub[1:]
		}
		trimLead(re.Sub[0])
	}
}

func optionalRun(re *syntax.Regexp) bool {
	switch re.Op {
	case syntax.OpStar, syntax.OpQuest:
	case syntax.OpRepeat:
		if re.Min != 0 {
			return false
		}
	default:
		return false
	}
	switch re.Sub[0].Op {
	case syntax.OpCharClass, syntax.OpAnyChar, syntax.OpAnyCharNotNL, syntax.OpLiteral:
		return true
	}
	return false
}

func emit(b *strings.Builder, re *syntax.Regexp) error {
	switch re.Op {
	case syntax.OpNoMatch:
		b.WriteString(`[^\s\S]`)
	case syntax.OpEmptyMatch:
	case syntax.OpLiteral:
		for _, r := range re.Rune {
			if re.Flags&syntax.FoldCase != 0 && unicode.SimpleFold(r) != r {
				b.WriteByte('[')
				for f := r; ; {
					classRune(b, f)
					if f = unicode.SimpleFold(f); f == r {
						break
					}
				}
				b.WriteByte(']')
			} else {
				literalRune(b, r)
			}
		}
	case syntax.OpCharClass:
		if len(re.Rune) == 2 && re.Rune[0] == 0 && re.Rune[1] == unicode.MaxRune {
			b.WriteString(`[\s\S]`)
			break
		}
		b.WriteByte('[')
		for i := 0; i < len(re.Rune); i += 2 {
			classRune(b, re.Rune[i])
			if re.Rune[i+1] != re.Rune[i] {
				b.WriteByte('-')
				classRune(b, re.Rune[i+1])
			}
		}
		b.WriteByte(']')
	case syntax.OpAnyCharNotNL:
		b.WriteString(`[^\n]`)
	case syntax.OpAnyChar:
		b.WriteString(`[\s\S]`)
	case syntax.OpBeginLine:
		b.WriteString(`(?<![^\n])`)
	case syntax.OpEndLine:
		b.WriteString(`(?![^\n])`)
	case syntax.OpBeginText:
		b.WriteString(`^`)
	case syntax.OpEndText:
		b.WriteString(`$`)
	case syntax.OpWordBoundary:
		b.WriteString(`\b`)
	case syntax.OpNoWordBoundary:
		b.WriteString(`\B`)
	case syntax.OpCapture:
		b.WriteByte('(')
		if err := emit(b, re.Sub[0]); err != nil {
			return err
		}
		b.WriteByte(')')
	case syntax.OpStar, syntax.OpPlus, syntax.OpQuest, syntax.OpRepeat:
		b.WriteString("(?:")
		if err := emit(b, re.Sub[0]); err != nil {
			return err
		}
		b.WriteByte(')')
		switch re.Op {
		case syntax.OpStar:
			b.WriteByte('*')
		case syntax.OpPlus:
			b.WriteByte('+')
		case syntax.OpQuest:
			b.WriteByte('?')
		case syntax.OpRepeat:
			switch {
			case re.Max == -1:
				fmt.Fprintf(b, "{%d,}", re.Min)
			case re.Max == re.Min:
				fmt.Fprintf(b, "{%d}", re.Min)
			default:
				fmt.Fprintf(b, "{%d,%d}", re.Min, re.Max)
			}
		}
		if re.Flags&syntax.NonGreedy != 0 {
			b.WriteByte('?')
		}
	case syntax.OpConcat:
		for _, sub := range re.Sub {
			if err := emit(b, sub); err != nil {
				return err
			}
		}
	case syntax.OpAlternate:
		b.WriteString("(?:")
		for i, sub := range re.Sub {
			if i > 0 {
				b.WriteByte('|')
			}
			if err := emit(b, sub); err != nil {
				return err
			}
		}
		b.WriteByte(')')
	default:
		return fmt.Errorf("unsupported regexp op %v", re.Op)
	}
	return nil
}

func literalRune(b *strings.Builder, r rune) {
	if strings.ContainsRune(`\^$.|?*+()[]{}/`, r) {
		b.WriteByte('\\')
		b.WriteRune(r)
		return
	}
	printable(b, r)
}

func classRune(b *strings.Builder, r rune) {
	if strings.ContainsRune(`\]^-[/`, r) {
		b.WriteByte('\\')
		b.WriteRune(r)
		return
	}
	printable(b, r)
}

func printable(b *strings.Builder, r rune) {
	if r > ' ' && r < 0x7f {
		b.WriteRune(r)
	} else {
		fmt.Fprintf(b, `\u{%x}`, r)
	}
}

